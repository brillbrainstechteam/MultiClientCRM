import type { CatalogueItem, FieldOwnershipMap, MediaAsset } from '../domain/types';

let mediaSeq = 0;
function image(itemId: string, isCover: boolean, caption: string, opts: Partial<MediaAsset> = {}): MediaAsset {
  mediaSeq += 1;
  return {
    id: `media_${mediaSeq}`,
    itemId,
    kind: 'image',
    url: `https://picsum.photos/seed/${itemId}-${mediaSeq}/640/640`,
    fileName: `${itemId}_${mediaSeq}.jpg`,
    isCover,
    order: mediaSeq,
    caption,
    customerVisible: true,
    status: 'ok',
    source: 'upload',
    ...opts,
  };
}
function video(itemId: string, caption: string): MediaAsset {
  mediaSeq += 1;
  return {
    id: `media_${mediaSeq}`,
    itemId,
    kind: 'video',
    url: `https://example-cdn.northline.test/videos/${itemId}.mp4`,
    fileName: `${itemId}_video.mp4`,
    isCover: false,
    order: mediaSeq,
    caption,
    customerVisible: true,
    status: 'ok',
    source: 'upload',
  };
}

/** Hybrid ownership (Requirement §D4): source owns identifiers/weight/price, CRM owns enrichment. */
function jewelleryOwnership(stale = false): FieldOwnershipMap {
  return {
    sku: { owner: 'source', stale },
    grossWeightGm: { owner: 'source', stale },
    metal: { owner: 'source', stale },
    purity: { owner: 'source', stale },
    price: { owner: 'source', stale },
    media: { owner: 'crm' },
    whatsappCaption: { owner: 'crm' },
    collections: { owner: 'crm' },
    tags: { owner: 'crm' },
  };
}

function crmOwnership(): FieldOwnershipMap {
  return {
    sku: { owner: 'crm' },
    price: { owner: 'crm' },
    media: { owner: 'crm' },
    whatsappCaption: { owner: 'crm' },
    collections: { owner: 'crm' },
    tags: { owner: 'crm' },
  };
}

function apparelOwnership(): FieldOwnershipMap {
  return {
    sku: { owner: 'source', connectorWriteable: false },
    price: { owner: 'source', connectorWriteable: false },
    fabric: { owner: 'source' },
    size: { owner: 'source' },
    media: { owner: 'source', connectorWriteable: false },
    whatsappCaption: { owner: 'crm' },
    collections: { owner: 'crm' },
    tags: { owner: 'crm' },
  };
}

