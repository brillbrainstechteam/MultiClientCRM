export function findTemplate(templateId: string): Template | undefined {
  return templates.find((template) => template.id === templateId);
}

export function templatesByFamily(familyId: string): Template[] {
  return templates.filter((template) => template.familyId === familyId).sort((a, b) => a.locale.localeCompare(b.locale));
}

export function existingTemplateNames(wabaId: string, excludeId?: string): string[] {
  return templates
    .filter((template) => template.wabaId === wabaId && template.id !== excludeId && template.crmState !== 'deleted')
    .map((template) => template.name);
}
