export function attemptsForTask(taskId: string): CallAttempt[] {
  return callAttempts
    .filter((attempt) => attempt.taskId === taskId)
    .sort((a, b) => new Date(a.startedAt).getTime() - new Date(b.startedAt).getTime());
}

export function findCallAttempt(attemptId: string): CallAttempt | undefined {
  return callAttempts.find((attempt) => attempt.id === attemptId);
}
