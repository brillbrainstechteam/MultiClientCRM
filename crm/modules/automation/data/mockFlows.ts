import type { AutomationFlow, FlowNode } from '../domain/types';
import { starterTemplates } from './starterTemplates';

function starterNodes(templateId: string): FlowNode[] {
  const template = starterTemplates.find((t) => t.id === templateId);
  if (!template) throw new Error(`Unknown starter template: ${templateId}`);
  return structuredClone(template.nodes);
}

